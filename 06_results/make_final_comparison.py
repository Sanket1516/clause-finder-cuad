"""Build 06_results/final_comparison.{json,md} and copy final-evaluation artifacts into 06_results/final/ — from SAVED files only.
    python 06_results/make_final_comparison.py"""
import json
import math
import shutil
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "03_experiments" / "final_eval"
OUT = ROOT / "06_results"
KS = ["1", "2", "4", "8", "16", "32", "64"]


def load(cfg, split):
    return json.loads((EV / cfg / f"{split}_metrics.json").read_text(encoding="utf-8"))


def preds(cfg, split):
    return [json.loads(l) for l in (EV / cfg / f"{split}_predictions.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]


def recalls(cfg, split, k="4"):
    return np.array([r["metrics"]["ranking"][k]["recall"] for r in sorted(preds(cfg, split), key=lambda r: r["query_id"]) if r["answerable"]])


def boot_ci(x, b=2000, seed=0):
    rng = np.random.default_rng(seed)
    m = x[rng.integers(0, len(x), size=(b, len(x)))].mean(axis=1)
    return [float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))]


def wilson(k, n, z=1.96):
    if n == 0:
        return [float("nan")] * 2
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [c - h, c + h]


def row(m):
    a, r, e = m["abstention"], m["retrieval_ranking_view"], m["retrieval_end_to_end"]
    c = a["confusion"]
    return {"n_answerable": m["n_answerable"], "n_unanswerable": m["n_unanswerable"], "threshold": m["threshold"],
            "recall": {k: r[k]["recall"] for k in KS}, "precision": {k: r[k]["precision"] for k in KS},
            "e2e_recall": {k: e[k]["recall"] for k in KS}, "e2e_precision": {k: e[k]["precision"] for k in KS},
            "false_abstentions": c["answerable_abstained_FN"], "correct_abstentions": c["unanswerable_abstained_TN"],
            "false_answers": c["unanswerable_answered_FP"], "answerable_answered": c["answerable_answered_TP"],
            "FAR": a["false_abstention_rate"], "CAR": a["correct_abstention_rate"], "false_answer_rate": a["false_answer_rate"],
            "AUROC": m["confidence_auroc_answerable_vs_unanswerable"], "doc_hit@1": m["document_hit_at_1"],
            "labels": m["label_counts_answerable"], "p50_ms": m["latency_ms"]["p50"], "p95_ms": m["latency_ms"]["p95"],
            "index_build_s": m["index_build_seconds"], "n_chunks": m["n_chunks"], "wall_s": m["wall_seconds"],
            "unanswerable_by_category": m["unanswerable_by_category"]}


def main():
    res = {c: {s: row(load(c, s)) for s in ("train", "test")} for c in ("baseline", "final")}
    stats = {}
    for s in ("train", "test"):
        b, f = recalls("baseline", s), recalls("final", s)
        stats[s] = {"final_R@4_bootstrap95": boot_ci(f), "baseline_R@4_bootstrap95": boot_ci(b), "paired_delta_R@4": float((f - b).mean()),
                    "paired_delta_bootstrap95": boot_ci(f - b), "bootstrap": {"B": 2000, "seed": 0, "resampled": "queries"}}
        for c in ("baseline", "final"):
            r = res[c][s]
            stats[s][f"{c}_CAR_wilson95"] = wilson(r["correct_abstentions"], r["n_unanswerable"])
            stats[s][f"{c}_FAR_wilson95"] = wilson(r["false_abstentions"], r["n_answerable"])
    out = {"results": res, "uncertainty": stats,
           "test_run_ledger": [json.loads(l) for l in (OUT / "test_runs" / "ledger.jsonl").read_text(encoding="utf-8").splitlines()],
           "note": "Uncertainty values are computed from the saved per-query predictions (percentile bootstrap over queries; Wilson interval for rates). Small samples: treat as rough."}
    (OUT / "final_comparison.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")

    L = ["# Final comparison (generated by make_final_comparison.py from saved metrics)", ""]
    for s in ("train", "test"):
        n = res["final"][s]
        L += [f"## {s} ({n['n_answerable']} answerable, {n['n_unanswerable']} unanswerable queries)", "",
              "| k | baseline R | final R | baseline P | final P |", "|---|---|---|---|---|"]
        for k in KS:
            L.append(f"| {k} | {res['baseline'][s]['recall'][k]:.4f} | {res['final'][s]['recall'][k]:.4f} | "
                     f"{res['baseline'][s]['precision'][k]:.4f} | {res['final'][s]['precision'][k]:.4f} |")
        L += ["", "| abstention | baseline | final |", "|---|---|---|"]
        for lab, key, den in (("false abstentions (answerable)", "false_abstentions", "n_answerable"),
                              ("correct abstentions (unanswerable)", "correct_abstentions", "n_unanswerable"),
                              ("false answers (unanswerable)", "false_answers", "n_unanswerable")):
            L.append(f"| {lab} | {res['baseline'][s][key]}/{res['baseline'][s][den]} | {res['final'][s][key]}/{res['final'][s][den]} |")
        L += [f"| AUROC | {res['baseline'][s]['AUROC']:.3f} | {res['final'][s]['AUROC']:.3f} |",
              f"| threshold | {res['baseline'][s]['threshold']:.4f} | {res['final'][s]['threshold']:.4f} |", ""]
    (OUT / "final_comparison.md").write_text("\n".join(L), encoding="utf-8")

    dest = OUT / "final"
    dest.mkdir(exist_ok=True)
    for c in ("baseline", "final"):
        for f in (EV / c).iterdir():
            t = dest / f"{c}_{f.name}"
            if not t.exists():
                shutil.copy(f, t)
    print("ok", len(list(dest.iterdir())), "files in 06_results/final")


if __name__ == "__main__":
    sys.exit(main())
